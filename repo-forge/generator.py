import json
import os
from pathlib import Path
from typing import List, Dict, Optional
from jinja2 import Template
from loguru import logger

class AppGenerator:
    def __init__(self, output_dir: str = "./workspace/apps"):
        self.output_dir = Path(output_dir)
        self.output_dir.mkdir(parents=True, exist_ok=True)

    def generate_app(self, project_name: str, selected_units: List[Dict], description: str = "") -> Dict:
        app_dir = self.output_dir / project_name
        app_dir.mkdir(parents=True, exist_ok=True)

        main_py = self._generate_main_py(project_name, selected_units)
        frontend_html = self._generate_frontend(project_name, selected_units)
        requirements = self._generate_requirements(selected_units)
        pyproject = self._generate_pyproject(project_name)

        (app_dir / "main.py").write_text(main_py, encoding="utf-8")
        (app_dir / "requirements.txt").write_text(requirements, encoding="utf-8")
        (app_dir / "pyproject.toml").write_text(pyproject, encoding="utf-8")

        static_dir = app_dir / "static"
        static_dir.mkdir(exist_ok=True)
        (static_dir / "index.html").write_text(frontend_html, encoding="utf-8")

        src_dir = app_dir / "src" / project_name.replace("-", "_").replace(" ", "_")
        src_dir.mkdir(parents=True, exist_ok=True)

        for unit in selected_units:
            unit_file = src_dir / f"{unit['type']}_{unit['name'].replace('.', '_')}.py"
            content = f'"""\n{unit["description"]}\nOriginal: {unit["original_file"]}\n"""\n\n'
            content += unit["source"]
            unit_file.write_text(content, encoding="utf-8")

        init_file = src_dir / "__init__.py"
        init_file.write_text("", encoding="utf-8")

        logger.info(f"Generated app scaffold at {app_dir}")
        return {
            "path": str(app_dir),
            "main_py": main_py,
            "frontend": frontend_html,
            "requirements": requirements,
            "selected_count": len(selected_units),
        }

    def _generate_main_py(self, project_name: str, selected_units: List[Dict]) -> str:
        module_name = project_name.replace("-", "_").replace(" ", "_")
        imports = []
        classes = []
        functions = []
        entry_points = []

        for unit in selected_units:
            if unit["type"] == "class":
                imports.append(f"from src.{module_name}.{unit['type']}_{unit['name'].replace('.', '_')} import {unit['name'].split('.')[0]}")
                classes.append(unit["name"].split(".")[0])
            elif unit["type"] == "function":
                imports.append(f"from src.{module_name}.{unit['type']}_{unit['name'].replace('.', '_')} import {unit['name']}")
                functions.append(unit["name"])

        import_block = "\n".join(sorted(set(imports)))

        template = Template('''
import logging
from fastapi import FastAPI, Request
from fastapi.responses import HTMLResponse, JSONResponse
from fastapi.staticfiles import StaticFiles
from fastapi.templating import Jinja2Templates
import uvicorn
import sys
import os

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "src"))

{{ import_block }}

logging.basicConfig(level=logging.INFO)
logger = logging.getLogger(__name__)

app = FastAPI(title="{{ project_name }}", description="{{ description }}")
app.mount("/static", StaticFiles(directory="static"), name="static")
templates = Jinja2Templates(directory="static")


@app.get("/", response_class=HTMLResponse)
async def home(request: Request):
    return templates.TemplateResponse("index.html", {"request": request})


@app.get("/api/health")
async def health():
    return {"status": "ok", "units": {{ selected_count }}}


{% for func in functions %}
@app.get("/api/{{ func }}")
async def call_{{ func }}():
    try:
        result = {{ func }}()
        return JSONResponse(content={"result": str(result)})
    except Exception as e:
        return JSONResponse(content={"error": str(e)}, status_code=500)

{% endfor %}
{% for cls in classes %}
@app.post("/api/{{ cls }}/invoke")
async def invoke_{{ cls }():
    try:
        instance = {{ cls }}()
        result = str(instance)
        return JSONResponse(content={"result": result})
    except Exception as e:
        return JSONResponse(content={"error": str(e)}, status_code=500)

{% endfor %}
if __name__ == "__main__":
    uvicorn.run("main:app", host="0.0.0.0", port=8000, reload=True)
''')
        return template.render(
            project_name=project_name,
            description=description or "Generated by RepoForge",
            import_block=import_block,
            selected_count=len(selected_units),
            functions=functions[:10],
            classes=classes[:10],
        )

