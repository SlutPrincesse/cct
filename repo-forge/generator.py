    def _generate_requirements(self, selected_units: List[Dict]) -> str:
        all_imports = set()
        for unit in selected_units:
            for imp in unit.get("imports", []):
                all_imports.add(imp)
        stdlib = {"os", "sys", "json", "re", "math", "datetime", "pathlib", "collections", "itertools", "functools", "typing", "dataclasses", "enum", "abc", "statistics", "random", "string", "time", "hashlib", "base64", "io", "csv", "sqlite3", "http", "urllib", "email", "xml", "html", "logging", "argparse", "configparser", "socket", "selectors", "ssl", "hashlib", "secrets", "getpass", "tempfile", "shutil", "glob", "fnmatch", "linecache", "textwrap", "string", "struct", "codecs", "unicodedata", "reprlib", "pprint", "copy", "pprint", "enum", "graphlib"}
        third_party = all_imports - stdlib
        base = ["fastapi==0.104.1", "uvicorn==0.24.0", "jinja2==3.1.2", "python-multipart==0.0.6"]
        for pkg in sorted(third_party):
            base.append(pkg)
        return "\n".join(base)

